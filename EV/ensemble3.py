# Main
# --------------------------------------------------------------------------- #
def main():
    t0 = time.time()
    train = pd.read_csv(TRAIN_PATH)
    test = pd.read_csv(TEST_PATH)
    print(f"train: {train.shape}   test: {test.shape}")

    train[TARGET] = train[TARGET].map({"Yes": 1, "No": 0})
    y = train[TARGET].values

    train_fe = engineer_features(train)
    test_fe = engineer_features(test)

    print("\nBuilding leak-free WOE / logit features...")
    woe_train, woe_test, glm_logit_cols = build_woe_features(train_fe, test_fe, y)
    print(f"  Added {woe_train.shape[1]} WOE/logit features "
          f"({len(glm_logit_cols)} of them logit-space, for the GLM)")

    cat_encoders = build_label_encoders(train_fe, RAW_CATEGORICAL + ENGINEERED_CATEGORICAL)
    train_enc = apply_label_encoders(train_fe, RAW_CATEGORICAL + ENGINEERED_CATEGORICAL, cat_encoders)
    test_enc = apply_label_encoders(test_fe, RAW_CATEGORICAL + ENGINEERED_CATEGORICAL, cat_encoders)

    base_numeric = RAW_NUMERIC + ENGINEERED_NUMERIC + ARTIFACT_FLAGS
    base_categorical = RAW_CATEGORICAL + ENGINEERED_CATEGORICAL
    woe_cols = [c for c in woe_train.columns if not c.startswith("logit_")]
    feature_cols = base_numeric + base_categorical + woe_cols

    X_xgb_lgb = pd.concat([train_enc[base_numeric + base_categorical], woe_train[woe_cols]], axis=1)[feature_cols]
    X_test_xgb_lgb = pd.concat([test_enc[base_numeric + base_categorical], woe_test[woe_cols]], axis=1)[feature_cols]

    X_cat = pd.concat([train_fe[base_numeric + base_categorical], woe_train[woe_cols]], axis=1)[feature_cols]
    X_test_cat = pd.concat([test_fe[base_numeric + base_categorical], woe_test[woe_cols]], axis=1)[feature_cols]
    for c in base_categorical:
        X_cat[c] = X_cat[c].astype(str)
        X_test_cat[c] = X_test_cat[c].astype(str)
    cat_feature_idx = [feature_cols.index(c) for c in base_categorical]

    # GLM feature set: logit-space encodings + standardized raw numerics
    glm_feature_cols = glm_logit_cols + RAW_NUMERIC + ARTIFACT_FLAGS
    X_glm = pd.concat([train_fe[RAW_NUMERIC + ARTIFACT_FLAGS], woe_train[glm_logit_cols]], axis=1)[glm_feature_cols]
    X_test_glm = pd.concat([test_fe[RAW_NUMERIC + ARTIFACT_FLAGS], woe_test[glm_logit_cols]], axis=1)[glm_feature_cols]

    print(f"\nTotal tree features: {len(feature_cols)} | GLM features: {len(glm_feature_cols)}")
    print(f"Seeds for bagging: {SEEDS}")

    print("\n" + "=" * 80 + "\nXGBoost (bagged)\n" + "=" * 80)
    oof_xgb, test_xgb = run_xgb_bagged(X_xgb_lgb, y, X_test_xgb_lgb, BEST_PARAMS_XGB, SEEDS)

    print("\n" + "=" * 80 + "\nLightGBM (bagged)\n" + "=" * 80)
    oof_lgb, test_lgb = run_lgb_bagged(X_xgb_lgb, y, X_test_xgb_lgb, BEST_PARAMS_LGB, SEEDS)

    print("\n" + "=" * 80 + "\nCatBoost (bagged)\n" + "=" * 80)
    oof_cat, test_cat = run_cat_bagged(X_cat, y, X_test_cat, BEST_PARAMS_CAT, cat_feature_idx, SEEDS)

    print("\n" + "=" * 80 + "\nGLM / logistic regression (bagged)\n" + "=" * 80)
    oof_glm, test_glm = run_glm_bagged(X_glm, y, X_test_glm, SEEDS)

    print("\n" + "=" * 80 + "\nSTACKING (4 diverse base learners)\n" + "=" * 80)
    stack_train = np.column_stack([oof_xgb, oof_lgb, oof_cat, oof_glm])
    stack_test = np.column_stack([test_xgb, test_lgb, test_cat, test_glm])

    meta = LogisticRegression(max_iter=1000)
    meta.fit(stack_train, y)
    stack_oof = meta.predict_proba(stack_train)[:, 1]
    stack_auc = roc_auc_score(y, stack_oof)

    print(f"Individual bagged OOF AUCs -> "
          f"XGB: {roc_auc_score(y, oof_xgb):.4f}  LGB: {roc_auc_score(y, oof_lgb):.4f}  "
          f"Cat: {roc_auc_score(y, oof_cat):.4f}  GLM: {roc_auc_score(y, oof_glm):.4f}")
    print(f"Meta-model weights: {dict(zip(['xgb', 'lgb', 'cat', 'glm'], meta.coef_[0]))}")
    print(f"STACKED OOF AUC: {stack_auc:.4f}")

    test_final = meta.predict_proba(stack_test)[:, 1]
    submission = pd.DataFrame({ID_COL: test[ID_COL], TARGET: test_final})
    submission.to_csv(SUBMISSION_PATH, index=False)
    print(f"\nSaved -> {SUBMISSION_PATH}")
    print(submission.head())
    print(f"\nTotal runtime: {(time.time() - t0) / 60:.1f} minutes")


if __name__ == "__main__":
    main()