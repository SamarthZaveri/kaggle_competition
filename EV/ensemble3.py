"""
EV Purchase Prediction: Ensemble v3
======================================
Goal: push stacked OOF AUC from 0.9422 -> ~0.946 by pulling levers that
v1/v2 did NOT test, instead of doing more of what already plateaued.

What changed vs v2:

1. NO re-tuning. v1 (40 trials, single split) vs v2 (25 trials, 3-fold
   objective) moved stacked OOF by +0.0001 and made XGB/Cat WORSE in
   isolation. That's proof tuning is not where the remaining signal is.
   Params below are fixed, sane defaults -- edit BEST_PARAMS_XGB/LGB/CAT
   if you want to drop in your own v1 or v2 best_params dicts instead.

2. MULTI-SEED BAGGING. Each tree model now runs N_SEEDS x 5-fold and
   averages OOF/test predictions across seeds. This reduces fold-split
   variance (not signal) -- cheap, reliable, usually worth 0.001-0.003
   AUC on a plateaued model, and costs no tuning time since tuning was
   removed.

3. A GLM (elastic-net logistic regression) fit directly on logit-encoded
   (WOE) features + standardized raw numerics. Rationale: three
   completely different tree libraries independently converged to the
   same ~0.941-0.942 ceiling regardless of how features were engineered,
   and CatBoost's #1 feature by far became master_logit_score (a sum of
   logits). That combination is the textbook signature of a target
   generated by a smooth ADDITIVE function in log-odds space -- exactly
   what a logistic regression is built to fit, and exactly what GBDTs
   are inefficient at approximating via splits. Whether or not the GLM
   beats the trees outright, it is a genuinely different model family
   (uncorrelated errors) and should add real value to the stack, unlike
   adding a 4th tree-based model.

4. Generator-artifact flags for the exact mass-point/invented spikes
   found in the forum thread ($96,749 appears 1,073x in train; the
   30,000 spike; the 60-65k range that Tilii confirmed the generator
   invented and doesn't exist in the original 10k-row dataset).

Run this AFTER you've already run oracle_check.py / ensemble_v2.py once
-- it reuses the same feature engineering and WOE approach as v2.
"""

